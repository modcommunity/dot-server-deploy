#!/usr/bin/env bash
#
# Write the files for running a server in Docker Compose or on a Pterodactyl panel.
#
#   tools/deploy-modes.sh --mode compose --out ./my-server --name "My server" --games gamemann/game-g2gfast
#   tools/deploy-modes.sh --mode pterodactyl --out ./panel --name "My server"
#   add --dry-run to list what would be written and write nothing
#
# Options: --name, --game, --games A,B, --port N, --max-players N, --rcon-port N,
# --domain D (compose: publish the WebSocket port on the loopback for nginx), --project DIR.
# There is no password option on purpose: secrets live in cfg/ files and are never written here.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODE="" OUT="" DRY=0 NAME="My TMC server" GAME="g2gfast" GAMES="gamemann/game-g2gfast"
PORT=6064 MAXP=64 RCON="" DOMAIN="" PROJECT="$ROOT"

die() { printf 'deploy-modes: %s\n' "$1" >&2; exit "${2:-1}"; }
while [ $# -gt 0 ]; do
    case "$1" in
        --mode)        MODE="${2:?--mode needs a value}"; shift 2 ;;
        --out)         OUT="${2:?--out needs a value}"; shift 2 ;;
        --name)        NAME="${2:?--name needs a value}"; shift 2 ;;
        --game)        GAME="${2:?--game needs a value}"; shift 2 ;;
        --games)       GAMES="${2:?--games needs a value}"; shift 2 ;;
        --port)        PORT="${2:?--port needs a value}"; shift 2 ;;
        --max-players) MAXP="${2:?--max-players needs a value}"; shift 2 ;;
        --rcon-port)   RCON="${2:?--rcon-port needs a value}"; shift 2 ;;
        --domain)      DOMAIN="${2:?--domain needs a value}"; shift 2 ;;
        --project)     PROJECT="${2:?--project needs a value}"; shift 2 ;;
        --dry-run)     DRY=1; shift ;;
        -h|--help)     sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) die "unknown option: $1" 2 ;;
    esac
done

case "$MODE" in compose|pterodactyl) ;; *) die "--mode must be compose or pterodactyl (host is setup.sh itself)" 2 ;; esac
[ -n "$OUT" ] || die "--out DIR is required" 2
for n in PORT MAXP; do case "${!n}" in ''|*[!0-9]*) die "$n must be a number: ${!n}" 2 ;; esac; done
[ -z "$RCON" ] && RCON=$((PORT + 1))
case "$RCON" in *[!0-9]*) die "--rcon-port must be a number" 2 ;; esac
# A quote or newline would break the .env line and the JSON, so refuse rather than escape.
case "$NAME$GAME$GAMES$DOMAIN" in *[\"\'\$\`\\]*|*$'\n'*) die "name, game, games and domain may not contain quotes, backslashes, \$ or newlines" 2 ;; esac

WROTE=()
put() {  # put <relative path>, content on stdin
    local rel="$1"
    WROTE+=("$rel")
    if [ "$DRY" -eq 1 ]; then cat >/dev/null; return 0; fi
    mkdir -p "$OUT/$(dirname "$rel")" && cat >"$OUT/$rel"
}

gen_compose() {
    local ctx df tcp
    ctx="$(cd "$PROJECT/.." && pwd)"
    df="$(basename "$PROJECT")/Dockerfile"
    tcp="\${TMC_PORT:-$PORT}:\${TMC_PORT:-$PORT}/tcp"
    [ -n "$DOMAIN" ] && tcp="127.0.0.1:$tcp"
    put .env <<EOF
# Non-secret settings only. Passwords live in cfg/ (cfg/rcon.yml is written once on first start).
TMC_NAME=$NAME
TMC_MAX_PLAYERS=$MAXP
TMC_GAME=$GAME
TMC_GAMES=$GAMES
TMC_PORT=$PORT
TMC_RCON_PORT=$RCON
UID=1000
GID=1000
EOF
    put docker-compose.yml <<EOF
# Generated by tools/deploy-modes.sh. Edit .env for settings and cfg/ for everything else.
services:
  server:
    build:
      context: $ctx
      dockerfile: $df
      args:
        TMC_BUILD_GAMES: none
    image: tmc-server:latest
    container_name: tmc-server
    restart: unless-stopped
    stop_grace_period: 30s
    user: "\${UID:-1000}:\${GID:-1000}"
    env_file: .env
    environment:
      TMC_GAMES_MODE: "hide"
      TMC_QUERY_BIND: "*"
    ports:
      - "$tcp"
      - "\${TMC_PORT:-$PORT}:\${TMC_PORT:-$PORT}/udp"
      - "127.0.0.1:\${TMC_RCON_PORT:-$RCON}:\${TMC_RCON_PORT:-$RCON}/tcp"
    volumes:
      - ./cfg:/srv/tmc/cfg
      - ./content:/srv/tmc/content
      - ./data:/srv/tmc/data
    healthcheck:
      test: ["CMD", "/srv/tmc/docker-healthcheck.sh"]
      interval: 30s
      timeout: 10s
      start_period: 40s
      retries: 3
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    deploy:
      resources:
        limits:
          memory: 1g
    logging:
      driver: json-file
      options:
        max-size: "10m"
        max-file: "3"
EOF
    local d
    for d in cfg content data; do
        WROTE+=("$d/")
        [ "$DRY" -eq 1 ] || mkdir -p "$OUT/$d"
    done
}

gen_pterodactyl() {
    local egg="$PROJECT/deploy/pterodactyl-egg.json" tmp
    [ -f "$egg" ] || die "$egg is missing" 1
    command -v python3 >/dev/null || die "python3 is needed to write the egg" 1
    tmp="$(mktemp -d)"
    python3 -I - "$egg" "$tmp" "$NAME" "$GAME" "$GAMES" "$MAXP" "$RCON" <<'PY' || { rm -rf "$tmp"; die "could not read the egg" 1; }
import json, sys
egg, tmp, name, game, games, maxp, rcon = sys.argv[1:8]
d = json.load(open(egg))
want = {"TMC_NAME": name, "TMC_GAME": game, "TMC_GAMES": games, "TMC_MAX_PLAYERS": maxp, "TMC_RCON_PORT": rcon}
for v in d["variables"]:
    if v["env_variable"] in want:
        v["default_value"] = want[v["env_variable"]]
json.dump(d, open(tmp + "/egg-tmc-server.json", "w"), indent=2)
open(tmp + "/install.sh", "w").write(d["scripts"]["installation"]["script"])
PY
    put egg-tmc-server.json <"$tmp/egg-tmc-server.json"
    put install.sh <"$tmp/install.sh"
    rm -rf "$tmp"
    put allocations.txt <<EOF
Allocations to give the server on the panel (Admin > Servers > Build Configuration):

  primary    $PORT   the game: wings publishes it for TCP (browsers) and UDP (desktop, A2S, DQP)
  additional $RCON   RCON, if you want a remote console; set the TMC_RCON_PORT variable to this number

Leave the Port variable empty: the startup command already passes the primary allocation.
Nginx in front of the primary allocation is unchanged: deploy/install-server-tls.sh --domain <name> --backend <node>:$PORT
Passwords are never startup variables. Put them in cfg/rcon.yml in the server's file manager.
EOF
}

"gen_$MODE"
printf '%s %s files in %s:\n' "$([ "$DRY" -eq 1 ] && echo "would write" || echo "wrote")" "$MODE" "$OUT"
printf '  %s\n' "${WROTE[@]}"
if [ "$MODE" = compose ]; then
    echo "next: cd $OUT, then start it with: docker compose up -d --build"
    [ -n "$DOMAIN" ] && echo "nginx (unchanged): $PROJECT/deploy/install-server-tls.sh --domain $DOMAIN --backend 127.0.0.1:$PORT"
else
    echo "next: import egg-tmc-server.json under Nests, create a server, add the allocations in allocations.txt"
fi
exit 0
